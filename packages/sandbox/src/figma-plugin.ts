import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import type { DesignFrame } from '@ci/core';
import { checkoutWorld, worldAfter } from './world/checkout.js';
import { SCENARIOS } from './world/scenarios.js';

/**
 * Generator of the "CI sandbox" Figma plugin (docs/TEST-DATA-GENERATOR.md, 4.2). The plugin is the Figma kit: the
 * REST API cannot create frames, so the frames of the world go into the plugin, and the designer's account runs it
 * in the sandbox file. `npm run sandbox:figma-plugin` rewrites figma-plugin/code.js and manifest.json; a test fails
 * when the committed files fall behind the world.
 */

export interface PluginFrame {
  id: string;
  page: string;
  name: string;
  texts: string[];
  transitions: string[];
}

export interface PluginWorld {
  /** Menu command → the frames the file must hold after it ("reset" holds none). */
  targets: Record<string, PluginFrame[]>;
}

export const PLUGIN_DIR = new URL('../figma-plugin/', import.meta.url);

const toPluginFrame = (f: DesignFrame): PluginFrame => ({ id: f.id, page: f.page, name: f.name, texts: f.texts, transitions: f.transitions });

/** Seed holds the base world; every Figma scenario gets a mutate command with the world after it alone. */
export function pluginWorld(): PluginWorld {
  const targets: Record<string, PluginFrame[]> = { seed: checkoutWorld().frames.map(toPluginFrame) };
  for (const s of SCENARIOS.filter((x) => x.source === 'figma')) targets[`mutate:${s.id}`] = worldAfter(s.id).frames.map(toPluginFrame);
  return { targets };
}

export function pluginFiles(world: PluginWorld = pluginWorld()): { manifest: string; code: string } {
  const runtime = readFileSync(new URL('runtime.js', PLUGIN_DIR), 'utf8');
  const menu = [
    { name: 'Seed', command: 'seed' },
    ...Object.keys(world.targets).filter((c) => c.startsWith('mutate:')).map((c) => ({ name: `Mutate: ${c.slice('mutate:'.length)}`, command: c })),
    { separator: true },
    { name: 'Reset', command: 'reset' },
  ];
  const manifest = {
    name: 'CI sandbox',
    id: 'ci-sandbox-seeder',
    api: '1.0.0',
    main: 'code.js',
    editorType: ['figma'],
    documentAccess: 'dynamic-page',
    networkAccess: { allowedDomains: ['none'] },
    menu,
  };
  const code = [
    '// Generated by `npm run sandbox:figma-plugin` from the world in packages/sandbox — do not edit.',
    `var WORLD = { targets: {${Object.entries(world.targets).map(([c, frames]) => `\n  ${JSON.stringify(c)}: [${frames.map((f) => `\n    ${JSON.stringify(f)}`).join(',')}\n  ]`).join(',')}\n} };`,
    '',
    runtime.trimEnd(),
    '',
    "runSandbox(figma, WORLD, figma.command).catch(function (e) { figma.closePlugin('CI sandbox failed: ' + ((e && e.message) || e)); });",
    '',
  ].join('\n');
  return { manifest: `${JSON.stringify(manifest, null, 2)}\n`, code };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { manifest, code } = pluginFiles();
  writeFileSync(new URL('manifest.json', PLUGIN_DIR), manifest);
  writeFileSync(new URL('code.js', PLUGIN_DIR), code);
  console.log('figma-plugin/manifest.json and code.js written — import manifest.json in Figma desktop (Plugins → Development)');
}
